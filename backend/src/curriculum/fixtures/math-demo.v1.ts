const TASK_TYPES = [
  'short_answer',
  'multiple_choice',
  'matching',
  'expression',
  'word_problem',
];
const DIFFICULTIES = [
  TaskDifficulty.BASIC,
  TaskDifficulty.STANDARD,
  TaskDifficulty.ADVANCED,
];

export function buildDemoCurricula(): CurriculumImportPayload[] {
  return (Object.keys(TRACK_TOPICS) as ExamTrack[]).map((examTrack) => {
    const topics = TRACK_TOPICS[examTrack].map(
      ([code, title, section, aliases], position) => ({
        code,
        title,
        section,
        aliases,
        position: position + 1,
      }),
    );
    const tasks = topics.flatMap((topic, topicIndex) =>
      Array.from({ length: 3 }, (_, variant) => {
        const answer = String((topicIndex + 1) * 10 + variant + 1);
        return {
          externalId: `DEMO-${examTrack}-${topic.code}-${variant + 1}`,
          topicCode: topic.code,
          taskType: TASK_TYPES[(topicIndex + variant) % TASK_TYPES.length],
          difficulty: DIFFICULTIES[variant],
          statement:
            `Демонстрационное задание для проверки механики платформы. ` +
            `Тема «${topic.title}», вариант ${variant + 1}. Введите контрольное число ${answer}.`,
          acceptedAnswers: [answer],
          solution: `Это синтетическая задача. Контрольный ответ: ${answer}.`,
          metadata: { synthetic: true, variant: variant + 1 },
        };
      }),
    );
    return {
      schemaVersion: 1 as const,
      examTrack,
      year: 2026,
      version: 'demo-2026.1',
      title: `Демо-кодификатор: ${trackLabel(examTrack)}`,
      sourceKind: CurriculumSourceKind.DEMO,
      metadata: {
        disclaimer:
          'Синтетические данные только для тестирования. Это не официальный банк ФИПИ.',
      },
      topics,
      tasks,
    };
  });
}

function trackLabel(track: ExamTrack) {
  if (track === ExamTrack.OGE) return 'ОГЭ математика';
  if (track === ExamTrack.EGE_BASE) return 'ЕГЭ математика, базовый уровень';
  return 'ЕГЭ математика, профильный уровень';
}
